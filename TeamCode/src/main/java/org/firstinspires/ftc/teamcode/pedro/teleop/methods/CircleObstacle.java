package org.firstinspires.ftc.teamcode.pedro.teleop.methods;

public class CircleObstacle {
    public double x, y, radius, influenceRadius, kRep;

    public CircleObstacle(double x, double y, double radius, double influenceRadius, double kRep) {
        this.x = x;
        this.y = y;
        this.radius = radius;
        this.influenceRadius = influenceRadius;
        this.kRep = kRep;
    }
}

